/**
 * 투자거울: 채팅 컴포넌트 (chat.js)
 * 요약 카드, 메시지 목록, 추천 질문 칩, 매매 확인 카드, 출처 링크, 로딩 인디케이터
 */

const ChatComponent = {
  render(container) {
    const state = window.store.getState();
    const summary = state.summary;

    container.innerHTML = `
      <div class="chat-container">
        <!-- Quick Summary Banner -->
        <div id="chat-summary-banner" class="summary-card">
          ${this.renderSummaryCard(summary)}
        </div>

        <!-- Pending Review Alert (if any) -->
        <div id="pending-review-banner">
          ${this.renderReviewAlert(state.pendingReviews)}
        </div>

        <!-- Messages Stream -->
        <div class="messages-stream" id="messages-stream">
          ${this.renderMessages(state.messages)}
          ${state.isLoadingChat ? this.renderLoadingIndicator() : ''}
        </div>

        <!-- Pending Trade Confirmation Card (if generated by AI/Vision) -->
        <div id="pending-trades-container">
          ${this.renderPendingTrades(state.pendingTrades)}
        </div>

        <!-- Quick Suggestions -->
        <div class="quick-chips">
          <button class="chip" data-prompt="요즘 시장 분위기 어때?">📊 시장 분위기 어때?</button>
          <button class="chip" data-prompt="오늘 삼성전자 왜 떨어졌어?">📉 오늘 삼성전자 왜 떨어졌어?</button>
          <button class="chip" data-prompt="삼성전자 10주 7만 원에 샀어">📝 삼성전자 10주 7만원에 샀어</button>
          <button class="chip" data-prompt="지난번에 판 거 잘한 거야?">🔍 지난번에 판 거 잘한 거야?</button>
          <button class="chip" data-prompt="삼성전자 지금 사도 돼?">🛡️ 삼성전자 지금 사도 돼?</button>
        </div>

        <!-- Input Area -->
        <div class="chat-input-wrapper">
          <input 
            type="file" 
            id="capture-file-input" 
            accept="image/*" 
            style="display:none;" 
          />
          <button type="button" class="btn-icon" id="btn-attach-capture" title="체결내역 캡처 이미지 첨부">
            📷
          </button>
          <textarea 
            id="chat-input-text" 
            placeholder="매매를 기록하거나 시장과 종목에 대해 질문하세요... (Enter로 전송)"
            rows="1"
          ></textarea>
          <button type="button" class="btn-primary btn-send" id="btn-send-chat">
            비춰 보기
          </button>
        </div>
      </div>
    `;

    this.bindEvents(container);
    this.scrollToBottom();
  },

  renderSummaryCard(summary) {
    if (!summary || !summary.metrics) {
      return `
        <div class="summary-loading">
          <span>데이터 요약을 불러오는 중입니다...</span>
        </div>
      `;
    }

    const m = summary.metrics;
    const t = summary.trend;
    const mt = summary.my_trades;
    const trendClass = t.label === '상승' ? 'trend-up' : t.label === '하락' ? 'trend-down' : 'trend-neutral';

    return `
      <div class="summary-header">
        <div class="summary-title">
          <span class="badge">코스피 시장 요약</span>
          <span class="period">${summary.period} (${summary.count}영업일)</span>
        </div>
        <div class="summary-trend ${trendClass}" title="최근 20일 평균 ${t.avg_recent} / 직전 20일 평균 ${t.avg_prev} · 단순 분류이며 예측이 아니에요">
          ${t.label} (${t.avg_diff > 0 ? '+' : ''}${t.avg_diff}%)
        </div>
      </div>
      <div class="summary-metrics-grid">
        <div class="metric-item">
          <span class="metric-label">최근 종가</span>
          <span class="metric-value">${m.latest.toLocaleString()} pt</span>
        </div>
        <div class="metric-item">
          <span class="metric-label">평균 / 최고 / 최저</span>
          <span class="metric-value-sub">${m.average} / ${m.max} / ${m.min}</span>
        </div>
        <div class="metric-item">
          <span class="metric-label">1년 변동 범위 위치</span>
          <div class="range-bar-wrapper">
            <div class="range-bar" style="width: ${summary.position}%;"></div>
            <span class="range-pct">${summary.position}%</span>
          </div>
        </div>
        <div class="metric-item">
          <span class="metric-label">내 매매 기록</span>
          <span class="metric-value-sub">매수 ${mt.buy_count}건 · 매도 ${mt.sell_count}건 (당시 기록 ${mt.at_time}건)</span>
        </div>
      </div>
    `;
  },

  renderReviewAlert(pendingReviews) {
    if (!pendingReviews || pendingReviews.length === 0) return '';
    return `
      <div class="review-alert-card" onclick="window.Main.switchTab('review')">
        <span class="alert-icon">🔔</span>
        <span class="alert-text">복기 시점이 도래한 매매가 <strong>${pendingReviews.length}건</strong> 있습니다. (7일·30일 복기 확인)</span>
        <button class="btn-sm btn-outline">복기하러 가기 &rarr;</button>
      </div>
    `;
  },

  renderMessages(messages) {
    if (!messages || messages.length === 0) {
      return `
        <div class="empty-chat-guide">
          <div class="guide-icon">🪞</div>
          <h3>투자거울에 오신 것을 환영합니다!</h3>
          <p>내 매매를 코스피 시장과 종목 흐름에 비춰 보며 투자를 복기하는 개인 AI 비서입니다.</p>
          <div class="guide-examples">
            <div class="guide-item">💡 "오늘 삼성전자 10주 7만 원에 샀어" &rarr; 매매 기록 카드 생성</div>
            <div class="guide-item">💡 "오늘 삼성전자 왜 떨어졌어?" &rarr; 코스피 대비 등락률 및 공시·뉴스 비교</div>
            <div class="guide-item">💡 "지난번에 판 거 잘한 거야?" &rarr; 매도 이유와 이후 흐름 복기</div>
          </div>
        </div>
      `;
    }

    return messages.map((m) => {
      const isUser = m.role === 'user';
      const formattedContent = this.formatMarkdown(m.content);
      const sourcesHtml = m.sources && m.sources.length > 0 ? this.renderSources(m.sources) : '';
      const offlineBadge = m.mode === 'offline'
        ? '<div class="offline-badge" title="AI가 아니라 저장된 요약만 보여 준 답변이에요">⚠️ AI 미연결 · 저장된 요약만 표시</div>'
        : '';

      return `
        <div class="message-row ${isUser ? 'user-row' : 'assistant-row'}">
          <div class="message-bubble ${isUser ? 'user-bubble' : 'assistant-bubble'}">
            ${offlineBadge}
            <div class="message-text">${formattedContent}</div>
            ${sourcesHtml}
          </div>
        </div>
      `;
    }).join('');
  },

  renderSources(sources) {
    const esc = window.escapeHtml;
    const items = sources.map((s) => `
      <li class="source-item">
        <a href="${esc(window.safeUrl(s.link))}" target="_blank" rel="noopener noreferrer">
          <span class="source-badge">[${esc(s.source || '참고자료')}]</span> ${esc(s.title)}
          ${s.pub_date ? `<span class="source-date">(${esc(s.pub_date)})</span>` : ''}
        </a>
      </li>
    `).join('');

    return `
      <div class="sources-box">
        <div class="sources-header">📌 판단 근거 및 출처</div>
        <ul class="sources-list">${items}</ul>
      </div>
    `;
  },

  renderPendingTrades(pendingTrades) {
    if (!pendingTrades || pendingTrades.length === 0) return '';

    const esc = window.escapeHtml;
    return pendingTrades.map((t, idx) => {
      const checks = t.needs_check || [];
      const warn = [];
      if (checks.includes('date')) warn.push('날짜를 캡처에서 읽지 못해 오늘로 넣었어요. 맞는지 확인해 주세요.');
      if (checks.includes('code') || !t.code) warn.push('종목코드를 찾지 못했어요. 데이터 관리 탭에서 코드와 함께 직접 입력해 주세요.');
      return `
      <div class="pending-trade-card" data-index="${idx}">
        <div class="card-title">
          <span>📝 매매 기록 확인 (${esc(t.date)})</span>
          <button class="btn-close" onclick="window.ChatComponent.discardPendingTrade(${idx})">&times;</button>
        </div>
        <div class="trade-details">
          <span class="trade-side ${t.side === 'buy' ? 'side-buy' : 'side-sell'}">${t.side === 'buy' ? '매수' : '매도'}</span>
          <strong>${esc(t.name)}</strong> (${esc(t.code || '코드 확인 필요')}) ${Number(t.qty)}주 @ ${Number(t.price).toLocaleString()}원
        </div>
        ${warn.length ? `<div class="pending-warn">${warn.map(esc).join('<br/>')}</div>` : ''}
        <div class="reason-section">
          <label>매매 이유 선택 (복기에 활용됩니다):</label>
          <div class="reason-chips">
            ${['성장성', '시장 흐름', '가격 하락', '뉴스·이슈', '기타'].map((r) => `
              <button type="button" class="chip-reason ${t.reason === r ? 'active' : ''}" 
                onclick="window.ChatComponent.selectReason(${idx}, '${r}')">${r}</button>
            `).join('')}
          </div>
        </div>
        <div class="card-actions">
          <button class="btn-primary btn-sm" onclick="window.ChatComponent.savePendingTrade(${idx})" ${t.code ? '' : 'disabled'}>
            기록 저장하기
          </button>
        </div>
      </div>
    `;
    }).join('');
  },

  renderLoadingIndicator() {
    return `
      <div class="message-row assistant-row">
        <div class="message-bubble assistant-bubble loading-bubble">
          <div class="pulsing-dots">
            <span class="dot"></span>
            <span class="dot"></span>
            <span class="dot"></span>
          </div>
          <span class="loading-text">비춰 보는 중...</span>
        </div>
      </div>
    `;
  },

  formatMarkdown(text) {
    if (!text) return '';
    let escaped = text
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');

    // Bold **text**
    escaped = escaped.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');
    // Line breaks
    escaped = escaped.replace(/\n/g, '<br/>');
    return escaped;
  },

  bindEvents(container) {
    const input = container.querySelector('#chat-input-text');
    const sendBtn = container.querySelector('#btn-send-chat');
    const attachBtn = container.querySelector('#btn-attach-capture');
    const fileInput = container.querySelector('#capture-file-input');

    const handleSend = () => {
      const text = input.value.trim();
      if (!text) return;
      input.value = '';
      window.Main.sendChatMessage(text);
    };

    sendBtn.addEventListener('click', handleSend);
    input.addEventListener('keydown', (e) => {
      if (e.key === 'Enter' && !e.shiftKey) {
        e.preventDefault();
        handleSend();
      }
    });

    // Quick chips
    container.querySelectorAll('.chip').forEach((chip) => {
      chip.addEventListener('click', () => {
        const prompt = chip.getAttribute('data-prompt');
        window.Main.sendChatMessage(prompt);
      });
    });

    // Capture file attachment
    attachBtn.addEventListener('click', () => fileInput.click());
    fileInput.addEventListener('change', async (e) => {
      if (e.target.files && e.target.files[0]) {
        await window.Main.handleScreenshotUpload(e.target.files[0]);
        fileInput.value = '';
      }
    });
  },

  selectReason(idx, reason) {
    const trades = [...window.store.getState().pendingTrades];
    if (trades[idx]) {
      trades[idx].reason = trades[idx].reason === reason ? null : reason;
      window.store.setState({ pendingTrades: trades });
      window.Main.renderCurrentTab();
    }
  },

  discardPendingTrade(idx) {
    const trades = [...window.store.getState().pendingTrades];
    trades.splice(idx, 1);
    window.store.setState({ pendingTrades: trades });
    window.Main.renderCurrentTab();
  },

  async savePendingTrade(idx) {
    const trades = [...window.store.getState().pendingTrades];
    const trade = trades[idx];
    if (!trade) return;

    try {
      await window.Api.addTrade(trade.date, {
        id: trade.id,
        side: trade.side,
        name: trade.name,
        code: trade.code,
        qty: trade.qty,
        price: trade.price,
        broker: trade.broker || null,
        // 이유를 고르지 않았으면 비워 둡니다 (임의로 채우지 않음)
        reason: trade.reason || null,
        source: trade.source || 'chat'
      });

      trades.splice(idx, 1);
      window.store.setState({ pendingTrades: trades });
      alert(`✅ ${trade.name} ${trade.side === 'buy' ? '매수' : '매도'} 기록을 저장했어요.`);
      window.Main.refreshData();
    } catch (err) {
      alert(`저장 실패: ${err.message}`);
    }
  },

  scrollToBottom() {
    const stream = document.getElementById('messages-stream');
    if (stream) {
      stream.scrollTop = stream.scrollHeight;
    }
  }
};

window.ChatComponent = ChatComponent;
